let day= 5;

switch(day){

    case 1:
        console.log("monday");
        break;

    case 2:
        console.log("tuesday");
        break;

    case 3:
         console.log("Wednesday");
        break;

    case 4:
         console.log("Thusday");
        break;

    case 5:
         console.log("Firday");
        break;

    case 6:
         console.log("Sturday");
        break;

    case 7:
         console.log("Sunday");
        break;

    default:
        console.log("Invalid day");
}